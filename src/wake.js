import { readFile } from "node:fs/promises";

export const WAKE_JOB = "boxci-wake";
export const REUSABLE_WAKE_PATH = ".github/workflows/boxci-wake.yml";

export async function wakeScriptBlock() {
  const helper = await readFile(
    new URL("../ci/wake.py", import.meta.url),
    "utf8",
  );
  return helper
    .split("\n")
    .map((l) => (l ? "          " + l : ""))
    .join("\n");
}

/** The consumer's small call; only the named CI secret is forwarded. */
export async function wakeJobYaml({
  pool_variable = "BOXCI_POOL",
  label,
  secret,
  fallback = "ubuntu-24.04",
}) {
  return `  ${WAKE_JOB}:
    if: github.event_name != 'pull_request' || github.event.pull_request.draft == false
    uses: ./${REUSABLE_WAKE_PATH}
    with:
      pool: \${{ vars.${pool_variable} }}
      runner-label: ${quoteWorkflow(label)}
      fallback-label: ${quoteWorkflow(fallback)}
    secrets:
      api-key: \${{ secrets.${secret} }}
`;
}

export async function reusableWakeWorkflow() {
  const job = (
    await legacyWakeJobYaml({
      label: "REPLACE_LABEL",
      secret: "REPLACE_SECRET",
      jobName: "wake",
    })
  )
    .replace("${{ vars.BOXCI_POOL }}", "${{ inputs.pool }}")
    .replace('"REPLACE_LABEL"', "${{ inputs.runner-label }}")
    .replace("${{ secrets.REPLACE_SECRET }}", "${{ secrets.api-key }}")
    .replace('"ubuntu-24.04"', "${{ inputs.fallback-label }}");
  return `# Generated by BoxCI. Shared by init and migrated CI workflows.
name: BoxCI wake

on:
  workflow_call:
    inputs:
      pool:
        type: string
        required: true
      runner-label:
        type: string
        required: true
      fallback-label:
        type: string
        default: ubuntu-24.04
    secrets:
      api-key:
        required: false
    outputs:
      runner:
        description: JSON runner labels, including hosted fallback
        value: \${{ jobs.wake.outputs.runner }}

permissions: {}

jobs:
${job}`;
}

/** Replace only a byte-recognized generated wake job; preserve application jobs. */
export async function upgradeWakeJob(content, options) {
  const lines = content.split("\n");
  const start = lines.findIndex((line) => line === `  ${WAKE_JOB}:`);
  if (start < 0) return content;
  let end = start + 1;
  while (end < lines.length && !/^  [A-Za-z0-9_-]+:|^[A-Za-z]/.test(lines[end]))
    end++;
  const before = lines.slice(start, end).join("\n").trimEnd();
  const caller = (await wakeJobYaml(options)).trimEnd();
  if (before === caller) return content;
  if (before !== (await legacyWakeJobYaml(options)).trimEnd())
    throw new Error(
      "The existing boxci-wake job has custom or different settings. It was preserved; review it before migrating to the reusable helper.",
    );
  return content.replace(before, caller);
}

export function quoteWorkflow(s) {
  return JSON.stringify(s);
}

/** Inline wake job YAML (same behaviour as generated boxci.yml). */
export async function legacyWakeJobYaml({
  pool_variable = "BOXCI_POOL",
  label,
  secret,
  fallback = "ubuntu-24.04",
  jobName = WAKE_JOB,
}) {
  const block = await wakeScriptBlock();
  const q = quoteWorkflow;
  return `  ${jobName}:
    if: github.event_name != 'pull_request' || github.event.pull_request.draft == false
    runs-on: ubuntu-24.04
    timeout-minutes: 7
    outputs:
      runner: \${{ steps.route.outputs.runner }}
    steps:
      - name: Wake InstaBox pool
        id: route
        env:
          BOXCI_POOL: \${{ vars.${pool_variable} }}
          BOXCI_RUNNER_LABEL: ${q(label)}
          BOXCI_API_KEY: \${{ secrets.${secret} }}
          BOXCI_FALLBACK_LABEL: ${q(fallback)}
          BOXCI_TRUSTED: \${{ github.event_name != 'pull_request' || github.event.pull_request.head.repo.full_name == github.repository }}
        shell: bash
        run: |
          python3 - <<'BOXCI_WAKE'
${block}
          BOXCI_WAKE
`;
}
